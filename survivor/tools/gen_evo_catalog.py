#!/usr/bin/env python3
"""Rebuilds section 10 (option catalog) of docs/evolution_overhaul.md from tools/evo_data.py.

Run after editing evo_data.py:  python tools/gen_evo_catalog.py
Only the text between the CATALOG markers is replaced.
"""
import copy
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import evo_data  # noqa: E402
import gen_data  # noqa: E402

DOC = os.path.join(ROOT, 'docs', 'evolution_overhaul.md')
START = '<!-- CATALOG:START (generated by tools/gen_evo_catalog.py; edit tools/evo_data.py instead) -->'
END = '<!-- CATALOG:END -->'


def build():
    abilities = copy.deepcopy(gen_data.ABILITIES)
    evo_data.apply(abilities)
    by_id = {a['id']: a for a in abilities}
    lines = []
    for n, c in enumerate(gen_data.CHARS, 1):
        lines.append('### 10.%d %s' % (n, c['name']))
        for aid in (c['weapon'], c['passive']):
            a = by_id[aid]
            lines.append('')
            lines.append('**%s** (A = %s, B = %s)' % (a['name'], a['branches'][0]['name'], a['branches'][1]['name']))
            lines.append('')
            lines.append('| id | Name | Slot | Behavior (card text) | Icon brief |')
            lines.append('|---|---|---|---|---|')
            for br in ('a', 'b'):
                for tier in (1, 2):
                    for o in evo_data.OPTIONS:
                        if o['ability'] == aid and o['branch'] == br and o['tier'] == tier:
                            assert '|' not in o['desc'] and '|' not in o['brief'], o['id']
                            lines.append('| `%s` | %s | %s · Lv%d | %s | %s |' % (o['id'], o['name'], br.upper(), 8 if tier == 1 else 16, o['desc'], o['brief']))
        lines.append('')
    return '\n'.join(lines)


def main():
    text = open(DOC, encoding='utf-8').read()
    a = text.index(START) + len(START)
    b = text.index(END)
    new = text[:a] + '\n\n' + build() + '\n' + text[b:]
    open(DOC, 'w', encoding='utf-8').write(new)
    print('catalog rebuilt: %d options' % len(evo_data.OPTIONS))


if __name__ == '__main__':
    main()
